    @Test
    fun `matches Dart VM order including ties`() {
        for ((n, expected) in vectors) {
            val keys = List(n) { ((it.toLong() * 7919 + 13) % 5).toInt() }
            val idx = MutableList(n) { it }
            DartSort.sort(idx) { a, b -> keys[a].compareTo(keys[b]) }
            assertEquals("n=$n", expected, idx.joinToString(","))
        }
    }

    @Test
    fun `sorts correctly`() {
        val list = MutableList(500) { (it * 7_654_321L % 1009).toInt() }
        DartSort.sort(list, naturalOrder())
        assertEquals(list.sorted(), list)
    }
