#!/usr/bin/env python3
"""Convert the Flutter ARB files (lib/l10n/app_*.arb) into Android string resources.

Output: core/l10n/src/main/res/values{,-en,-es}/strings.xml

Rules (keep in sync with core/l10n/README.md):
- Resource names keep the ARB key verbatim (camelCase), so specs that cite ARB keys map 1:1.
- values/ is German: app_de.arb is the Flutter template and Flutter falls back to it.
- Placeholders become positional args in the order of the @key.placeholders metadata
  (or order of first appearance when there is no metadata):
  int -> %N$d, everything else -> %N$s. A comment above each string lists the arg order.
- ICU plurals become <plurals>. An explicit =0 branch is emitted as an extra string
  "<key>_zero" because Android never selects quantity "zero" for de/en/es; callers use
  pluralStringResourceWithZero() from :core:l10n. =1 maps to quantity "one".
- Strings without args that contain '%' get formatted="false".

Usage: python3 tools/arb2xml.py [repo_root]
"""
import json
import os
import re
import sys
from xml.sax.saxutils import escape

ROOT = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", ".."))
ARB_DIR = os.path.join(ROOT, "lib", "l10n")
OUT = os.path.join(ROOT, "android-native", "core", "l10n", "src", "main", "res")
LANGS = {"de": "values", "en": "values-en", "es": "values-es"}

PLACEHOLDER = re.compile(r"\{(\w+)\}")


def android_escape(text: str) -> str:
    text = escape(text)  # & < >
    text = text.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"')
    text = text.replace("\n", "\\n").replace("\t", "\\t")
    if text.startswith("@") or text.startswith("?"):
        text = "\\" + text
    return text


def arg_order(key: str, value: str, meta: dict) -> list:
    names = list((meta.get("placeholders") or {}).keys())
    for n in PLACEHOLDER.findall(value):
        if n not in names:
            names.append(n)
    return names


def arg_types(meta: dict) -> dict:
    return {n: (p or {}).get("type", "String") for n, p in (meta.get("placeholders") or {}).items()}


def render(value: str, order: list, types: dict):
    """Returns (escaped_text, has_args)."""
    has_args = bool(order) and bool(PLACEHOLDER.search(value))
    if has_args:
        value = value.replace("%", "%%")

    def repl(m):
        name = m.group(1)
        if name not in order:
            return m.group(0)
        idx = order.index(name) + 1
        conv = "d" if types.get(name) == "int" else "s"
        return f"%{idx}${conv}"

    out = PLACEHOLDER.sub(repl, value) if has_args else value
    return android_escape(out), has_args


def split_plural(value: str):
    """Parse '{count, plural, =0{..} =1{..} other{..}}' possibly with prefix/suffix text."""
    m = re.search(r"\{(\w+),\s*plural,", value)
    if not m:
        return None
    var = m.group(1)
    start = m.start()
    i = m.end()
    depth = 1
    branches = {}
    while i < len(value) and depth > 0:
        while i < len(value) and value[i].isspace():
            i += 1
        if value[i] == "}":
            depth -= 1
            i += 1
            break
        sel = re.match(r"(=\d+|zero|one|two|few|many|other)\s*\{", value[i:])
        if not sel:
            raise ValueError(f"Cannot parse plural: {value}")
        i += sel.end()
        d, j = 1, i
        while d:
            if value[j] == "{":
                d += 1
            elif value[j] == "}":
                d -= 1
            j += 1
        branches[sel.group(1)] = value[i:j - 1]
        i = j
    prefix, suffix = value[:start], value[i:]
    return var, prefix, branches, suffix


def convert(lang: str, data: dict, template: dict) -> str:
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             f"<!-- GENERATED by tools/arb2xml.py from lib/l10n/app_{lang}.arb. Do not edit. -->",
             '<resources xmlns:tools="http://schemas.android.com/tools" tools:ignore="MissingTranslation,UnusedResources,TypographyEllipsis,TypographyDashes,PluralsCandidate,StringFormatCount">']
    for key, value in data.items():
        if key.startswith("@"):
            continue
        meta = template.get("@" + key) or data.get("@" + key) or {}
        types = arg_types(meta)
        plural = split_plural(value)
        if plural:
            var, prefix, branches, suffix = plural
            order = arg_order(key, prefix + " ".join(branches.values()) + suffix, meta)
            if var not in order:
                order.insert(0, var)
            types.setdefault(var, "int")
            arg_doc = ", ".join(f"{n}:{types.get(n, 'String')}" for n in order)
            lines.append(f"    <!-- plural args: {arg_doc} -->")
            if "=0" in branches:
                text, _ = render(prefix + branches["=0"] + suffix, order, types)
                lines.append(f'    <string name="{key}_zero">{text}</string>')
            lines.append(f'    <plurals name="{key}">')
            one = branches.get("=1", branches.get("one"))
            if one is not None:
                text, _ = render(prefix + one + suffix, order, types)
                lines.append(f'        <item quantity="one">{text}</item>')
            for q in ("few", "many"):
                if q in branches:
                    text, _ = render(prefix + branches[q] + suffix, order, types)
                    lines.append(f'        <item quantity="{q}">{text}</item>')
            text, _ = render(prefix + branches["other"] + suffix, order, types)
            lines.append(f'        <item quantity="other">{text}</item>')
            lines.append("    </plurals>")
            continue
        order = arg_order(key, value, meta)
        text, has_args = render(value, order, types)
        attrs = ""
        if has_args:
            lines.append(f"    <!-- args: {', '.join(n + ':' + types.get(n, 'String') for n in order)} -->")
        elif "%" in value:
            attrs = ' formatted="false"'
        lines.append(f'    <string name="{key}"{attrs}>{text}</string>')
    lines.append("</resources>")
    return "\n".join(lines) + "\n"


def main():
    template = json.load(open(os.path.join(ARB_DIR, "app_de.arb"), encoding="utf-8"))
    for lang, folder in LANGS.items():
        data = json.load(open(os.path.join(ARB_DIR, f"app_{lang}.arb"), encoding="utf-8"))
        os.makedirs(os.path.join(OUT, folder), exist_ok=True)
        with open(os.path.join(OUT, folder, "strings.xml"), "w", encoding="utf-8") as f:
            f.write(convert(lang, data, template))
        print(f"{lang}: {sum(1 for k in data if not k.startswith('@'))} entries -> {folder}/strings.xml")


if __name__ == "__main__":
    main()
